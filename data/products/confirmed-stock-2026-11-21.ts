const stockById = new Map<string, readonly [string, string]>(
  confirmedStockBatch.map(([id, partNo, brand]) => [id, [partNo, brand] as const]),
);

export function applyConfirmedMrtStock(product: Product): Product {
  const match = stockById.get(product.id);
  if (
    !match ||
    match[0] !== product.partNo ||
    match[1] !== product.brand ||
    product.partNumberOnly ||
    product.inquiryOnly ||
    product.dataQuality === "needs_review" ||
    product.crossReferences?.some((reference) =>
      typeof reference !== "string" &&
      reference.relationType === "replaced_by" &&
      reference.verificationStatus === "verified"
    )
  ) {
    return product;
  }

  return {
    ...product,
    stockStatus: "in_stock",
    checkAvailability: false,
    mrtStockEvidence: {
      status: "in_stock",
      source: "internal_record",
      checkedAt: snapshotDate,
    },
  };
}
