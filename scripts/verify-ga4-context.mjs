import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';

const repo = process.cwd();
const require = createRequire(path.join(repo, 'package.json'));
const ts = require('typescript');
const source = fs.readFileSync(path.join(repo, 'lib/analytics/ga-context.ts'), 'utf8');
const compiled = ts.transpile(source, { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 });
const origin = 'https://www.mrtsupplier.com';
const campaign = 'utm_source=facebook&utm_medium=paid_social&utm_campaign=th_aircompressor_smalltest_2026q4&utm_content=partno_check_a';
const rows = [];
function environment(query = '') {
  const exports = {}, window = { location: new URL(origin + '/th/applications/air-compressor-generator' + query) };
  const sandbox = { exports, window, document: { referrer: 'https://example.com/private?email=not-real@example.invalid#private' }, URL };
  vm.createContext(sandbox);
  vm.runInContext(compiled, sandbox);
  // Test exactly the serialized pre-tag bootstrap used in SSR, not a parallel fixture implementation.
  vm.runInContext(exports.googleContextBootstrapScript(), sandbox);
  return { exports, window, sandbox };
}
function check(name, run) { run(); rows.push({ test: name, result: 'PASS' }); }
const plain = value => JSON.parse(JSON.stringify(value));
check('clean URL has no invented campaign', () => assert.deepEqual(plain(environment().window.__mrtGAContext.campaign), {}));
check('valid campaign values and id', () => {
  const e = environment('?' + campaign + '&utm_id=mrt_2026q4');
  assert.deepEqual(plain(e.window.__mrtGAContext.campaign), { campaign_source: 'facebook', campaign_medium: 'paid_social', campaign_name: 'th_aircompressor_smalltest_2026q4', campaign_content: 'partno_check_a', campaign_id: 'mrt_2026q4' });
});
check('URL context has no query/hash; referrer only external origin', () => {
  const e = environment('?' + campaign + '&fbclid=TEST&email=not-real%40example.invalid#private');
  assert.equal(e.window.__mrtGAContext.page.page_location, origin + '/th/applications');
  assert.equal(e.window.__mrtGAContext.page.page_referrer, 'https://example.com');
  assert.equal(JSON.stringify(e.window.dataLayer).includes('fbclid'), false);
  assert.equal(JSON.stringify(e.window.dataLayer).includes('example.invalid'), false);
});
check('unknown keys and utm_term excluded', () => {
  const e = environment('?' + campaign + '&q=private&unknown=private&utm_term=private');
  assert.equal(JSON.stringify(e.window.dataLayer).includes('private'), false);
  assert.equal(Object.keys(e.window.__mrtGAContext.campaign).length, 4);
});
for (const [name, value] of [['oversized', 'x'.repeat(101)], ['email', 'not-real@example.invalid'], ['phone', '0812345678'], ['URL', 'https://example.invalid'], ['credential', 'Bearer_secret'], ['control', 'facebook\r\nprivate']]) {
  check('reject ' + name + ' without losing safe fields', () => {
    const e = environment('?utm_source=' + encodeURIComponent(value) + '&utm_medium=paid_social');
    assert.equal(e.window.__mrtGAContext.campaign.campaign_source, undefined);
    assert.equal(e.window.__mrtGAContext.campaign.campaign_medium, 'paid_social');
  });
}
check('trim accepted; duplicate key rejected', () => {
  const e = environment('?utm_source=%20facebook%20&utm_medium=paid_social&utm_medium=email');
  assert.equal(e.window.__mrtGAContext.campaign.campaign_source, 'facebook');
  assert.equal(e.window.__mrtGAContext.campaign.campaign_medium, undefined);
});
check('SPA context updates before event; campaign cannot be overwritten', () => {
  const e = environment('?' + campaign), initial = JSON.stringify(e.window.__mrtGAContext.campaign);
  const count = e.window.dataLayer.length;
  e.window.location = new URL(origin + '/en/products?utm_source=other&email=not-real%40example.invalid');
  e.exports.updateGooglePageContext(e.window.location.href, origin + '/th?notes=private');
  assert.equal(JSON.stringify(e.window.__mrtGAContext.campaign), initial);
  const later = e.window.dataLayer.slice(count);
  assert.equal(later.length, 1);
  assert.equal(later[0][0], 'set');
  assert.equal(later[0][1].page_location, origin + '/en/products');
  assert.equal(later[0][1].campaign_source, undefined);
});
check('bootstrap idempotent; no config or page_view generated by helper', () => {
  const e = environment('?' + campaign), count = e.window.dataLayer.length;
  vm.runInContext(e.exports.googleContextBootstrapScript(), e.sandbox);
  assert.equal(e.window.dataLayer.length, count);
  assert(e.window.dataLayer.every(entry => entry[0] === 'set'));
});
console.log(JSON.stringify({ cases: rows.length, rows, real_network_requests: 0 }));
